/**
 * Regenerates src/content/cities/index.ts from the city files present.
 *
 * City pages are written one file per city so several people (or agents) can
 * add them at once without colliding. This script is what turns that folder
 * back into a single typed array.
 *
 *   node tools/build-city-index.mjs
 */
import { readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const DIR = "src/content/cities";

const camel = (slug) =>
  slug.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

const slugs = readdirSync(DIR)
  .filter((f) => f.endsWith(".ts") && f !== "index.ts")
  .map((f) => f.replace(/\.ts$/, ""))
  .sort();

const imports = slugs
  .map((s) => `import { ${camel(s)} } from "./${s}";`)
  .join("\n");

const entries = slugs.map((s) => `  ${camel(s)},`).join("\n");

writeFileSync(
  join(DIR, "index.ts"),
  `import type { CityDefinition } from "@/types/content";
${imports}

/**
 * City landing pages, nested under their county.
 *
 * GENERATED by tools/build-city-index.mjs — do not edit by hand. Add a city by
 * creating src/content/cities/<slug>.ts exporting a camelCase const named after
 * the slug, then re-run the script.
 */
export const cities: CityDefinition[] = [
${entries}
];

export function getCityBySlug(slug: string): CityDefinition | undefined {
  return cities.find((c) => c.slug === slug);
}

export function getCitiesByCounty(countySlug: string): CityDefinition[] {
  return cities
    .filter((c) => c.countySlug === countySlug)
    .sort((a, b) => a.cityName.localeCompare(b.cityName));
}
`,
);

console.log(`Wrote ${DIR}/index.ts with ${slugs.length} cities.`);
